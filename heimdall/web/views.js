export function hypothesesGrid(doc) {
  const hyps = list(doc.hypotheses);
  if (!hyps.length) return empty("No target hypothesis record. Field candidates carry their own competing explanations (open a candidate).");
  const evidence = new Map(list(doc.evidence).map((e) => [e.evidence_id, e]));
  const open = hyps.filter((x) => ["CANNOT_EXCLUDE", "NOT_ASSESSABLE"].includes(x.status)).map((x) => x.title || x.slug);
  const ev = (id, kind) => {
    const e = evidence.get(id);
    return `<li><button type="button" class="text-button" data-action="reference" data-id="evidence[${h(id)}]">${h(id)}</button> <span class="ev-${kind}">${kind}</span>${e ? `<small>${h(e.statement || "")}${e.dependency_group ? ` · group ${h(e.dependency_group)}` : ""}</small>` : ""}</li>`;
  };
  return `${open.length ? `<p class="notice compact">Open alternatives (not excluded): ${h(open.join("; "))}. A SUPPORTED hypothesis is favoured only over the alternatives that were tested.</p>` : ""}
    <div class="hyp-grid">${hyps.map((x) => `<article class="hyp" aria-label="${h(x.title || x.slug)}">
      <header><h4>${h(x.title || x.slug)}</h4>${badge(x.status, x.status === "SUPPORTED" ? "good" : "warn")}</header>
      ${para(x.summary)}
      <h5>Supporting</h5><ul>${list(x.supporting_evidence).map((id) => ev(id, "supports")).join("") || "<li class=\"compact\">None recorded</li>"}</ul>
      <h5>Contradicting</h5><ul>${list(x.contradicting_evidence).map((id) => ev(id, "contradicts")).join("") || "<li class=\"compact\">None recorded</li>"}</ul>
      ${list(x.tests_run).length ? `<h5>Tests run</h5><p class="compact">${h(x.tests_run.join("; "))}</p>` : ""}
      ${list(x.tests_unavailable).length ? `<h5>Tests unavailable</h5>${x.tests_unavailable.map((t) => para(typeof t === "string" ? t : `${t.test || t.name}: ${t.reason || ""}`)).join("")}` : ""}
      ${list(x.assumptions).length ? `<h5>Assumptions</h5><p class="compact">${h(x.assumptions.join("; "))}</p>` : ""}
      ${list(x.limitations).length ? `<h5>Limitations</h5><p class="compact">${h(x.limitations.join("; "))}</p>` : ""}
      ${x.suggested_next_step ? `<h5>Discriminating next step</h5>${para(x.suggested_next_step)}` : ""}
    </article>`).join("")}</div>`;
}

export function deeperPage(state) {
  const doc = state.doc || {};
  if (doc.run_id) return group("Candidates and their explanations", para("Open a candidate (map or Quick answer) to see its evidence graph, dependency groups and competing explanations."));
  const p = state.patterns;
  const dims = list(p?.dimensions);
  return `${group("Competing hypotheses", hypothesesGrid(doc))}
    ${group("Patterns across dimensions", state.panelErrors.patterns ? empty(`Patterns unavailable: ${state.panelErrors.patterns}`, true) :
      `<div class="dims">${dims.map((d) => `<button type="button" class="dim" data-action="dimension" data-id="${h(d.dimension)}"><strong>${h(label(d.dimension))}</strong>${badge(label(d.status), ["NOT_RUN", "NOT_ASSESSABLE", "INSUFFICIENT_INPUTS"].includes(d.status) ? "warn" : "good")}<small>${h(d.finding || d.reason || "")}</small></button>`).join("")}</div>
      ${list(p?.missing).length ? para(`Missing dimensions: ${p.missing.map((m) => `${m.dimension}${m.reason ? ` (${m.reason})` : ""}`).join("; ")}.`) : ""}
      ${para(p?.cross_dimension?.note)}`)}
    ${state.record?.kind !== "run" && (doc.target?.target_id || "").startsWith("NASA-") ? group("Follow-up plan", stack([action("Open discriminating follow-up actions", "followup", doc.target.target_id, "Hypotheses distinguished, cost, budget, stopping reason")])) : ""}
    ${group("Not available in this backend", list(state.capabilities?.not_available).length
      ? table(["Analysis", "State", "Why"], state.capabilities.not_available.map((n) => [h(label(n.id)), h(label(n.state)), h(n.reason)]))
      : para("Capabilities could not be loaded. Composition and thermal interpretation, period search and cross-detector stacking are not offered without them."))}`;
}

