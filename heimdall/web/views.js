// Inspector pages: Quick answer -> Evidence -> Deeper dive -> History. They render backend records verbatim
// (claim types, statuses, gates); nothing scientific is recomputed in the browser.
import { action, badge, details, empty, facts, finite, group, h, json, label, list, number, obsAction, para, stack, table } from "./records.js";

const OUTCOME_TEXT = {
  LIMITED_BY_DATA: "Limited by data: the available observations cannot support this test. This is a complete outcome, not \"nothing found\".",
  NOT_ASSESSABLE: "Not assessable with the recorded inputs. This is not a non-detection.",
  INCONCLUSIVE: "Inconclusive: the evidence does not separate the competing explanations.",
  CANDIDATE: "Candidate: detection-shaped result from a method that is not validated on real data.",
  CONSISTENT_WITH: "Consistent with: not contradicted by the evidence. It is not the same as supported or confirmed.",
  MEASUREMENT: "Measurement: a recorded value with uncertainty. A forced flux is a measurement, not necessarily a detection.",
  NON_DETECTION: "Non-detection under the stated sensitivity.",
  UPPER_LIMIT: "Upper limit: the quantity is below the stated value.",
  BLOCKED: "Blocked: the analysis could not run. Earlier usable results are unaffected.",
  DETECTION: "Detection by a method validated for this use.",
};

export function plainClaim(type) { return OUTCOME_TEXT[type] || ""; }

export function value(v) {
  const fmt = (x) => Array.isArray(x) ? x.map((y) => number(y, 4)).join(", ") : finite(x) ? number(x, 4) : x ?? "—";
  return `${fmt(v.value)}${v.uncertainty != null ? ` ± ${fmt(v.uncertainty)}` : ""}${v.unit ? ` ${v.unit}` : ""}`;
}

export function statusChips(doc, claim) {
  return `<div class="status-grid" role="list">
    <div role="listitem"><span>Execution (software)</span>${badge(label(doc?.status?.execution || "—"), "good")}</div>
    <div role="listitem"><span>Scientific test status</span>${badge(label(doc?.status?.test_status || "—"), "warn")}</div>
    ${claim ? `<div role="listitem"><span>Claim</span>${badge(claim.claim_type, "claim")}</div>
    <div role="listitem"><span>Method validity</span>${badge(label(claim.strength || claim.method_validation?.state || "Not recorded"), "warn")}</div>` : ""}
  </div>`;
}

export function answerPage(state) {
  const doc = state.doc || {};
  if (state.record?.kind === "field") return coveragePage(state);
  if (doc.run_id) return runAnswer(state);
  const claims = state.claims;
  const head = list(claims?.claims).find((c) => c.claim_id === claims?.headline_claim);
  const synthetic = doc.data_origin === "SYNTHETIC";
  const latestUsable = state.versions?.latest_usable;
  const attempt = state.attempt;
  const failedAttempt = attempt && attempt.investigation_id !== doc.investigation_id && attempt.investigation_id !== latestUsable;
  return `${synthetic ? `<p class="synthetic-flag">SYNTHETIC · NOT REAL DATA</p>` : ""}
    ${synthetic ? "" : motionJourney(doc, head)}
    <section class="quick-answer" aria-labelledby="qa-title"><h3 id="qa-title">Quick answer</h3>
      <p>${h(claims?.quick_answer || (state.panelErrors.claims ? "The gated quick answer could not be loaded." : "Loading the gated answer…"))}</p>
      <p class="compact">Regenerated by the backend from the headline claim after its defensibility gate. ${claims?.saved_quick_answer && claims.saved_quick_answer !== claims.quick_answer ? "The originally saved wording differs and is not authoritative." : ""}</p></section>
    ${statusChips(doc, head)}
    ${state.panelErrors.claims ? empty(`Claims unavailable: ${state.panelErrors.claims}`, true) : ""}
    ${head ? group("What the headline claim says", `<p class="claim-type">${h(head.claim_type)}${head.downgraded_from ? ` <small>(downgraded from ${h(head.downgraded_from)})</small>` : ""}</p>
      ${para(plainClaim(head.claim_type))}${para(head.statement)}
      ${list(head.values).length ? table(["Quantity", "Value"], head.values.map((v) => [h(label(v.name || v.quantity)), h(value(v))])) : ""}
      <h4>What this does not establish</h4>${list(head.does_not_establish).map((x) => `<p class="compact">• ${h(x)}</p>`).join("") || para("Not stated.")}
      ${stack([action("Open the full claim and its gate checks", "claim", head.claim_id, `${list(head.gate?.checks).length} checks · ${head.gate?.passed ? "gate passed" : "gate failed"}`)])}`) : ""}
    ${doc.investigation_id && latestUsable && doc.investigation_id !== latestUsable ? `<p class="notice compact">You are viewing an older immutable version. The latest usable result is ${h(latestUsable)}.</p>
      ${stack([action("Open the latest usable result", "version", latestUsable)])}` : ""}
    ${failedAttempt ? group("Latest attempt (did not replace this result)", para(`${attempt.investigation_id}: ${label(attempt.status?.execution)}. ${attempt.status?.reason || ""}`) +
      stack([action("Inspect the latest attempt", "version", attempt.investigation_id, "Separate from the usable result")])) : ""}
    ${facts([["Observations measured", doc.coverage?.n_measured], ["Epochs", doc.coverage?.n_epochs], ["Reference", doc.reference?.catalogue], ["Saved", doc.created_at?.slice(0, 19)?.replace("T", " ")], ["Data origin", doc.data_origin]])}
    ${doc.investigation_id ? group("Next", stack([action("Evidence behind this answer", "tab", "evidence"), action("Competing hypotheses and patterns", "tab", "deeper"),
      action("Download readable report (.md)", "export", "md"), action("Download structured report (.json)", "export", "json"),
      ...(doc.target?.target_id?.startsWith("NASA-") || state.record?.kind === "target" ? [action("Prepare a new run of this target", "submit-target", doc.target?.target_id || state.record?.id, "Explicit: may queue archive work")] : [])])) : ""}`;
}

// Plain-language lead and the four-step evidence journey for a completed real motion analysis. Every number is read from the
// stored record; nothing is computed beyond combining the stored east/north uncertainties into one for the total speed.
function motionJourney(doc, head) {
  const m = doc.analyses?.motion;
  const fit = m?.fitted_velocity_arcsec_yr, cat = m?.catalogue_velocity_arcsec_yr, cov = doc.coverage || {};
  if (m?.status !== "COMPLETED" || doc.data_origin !== "REAL" || !Number.isFinite(fit?.total) || !Number.isFinite(cat?.total)) return "";
  const sigma = Math.hypot(fit.east * fit.sigma_east, fit.north * fit.sigma_north) / fit.total;
  const catName = doc.reference?.catalogue || "the reference catalogue";
  const name = doc.target?.name?.split(" (")[0] || "The target";
  const days = Math.round(m.baseline_days);
  const pCat = m.chi2?.catalogue?.sigma_equivalent, thr = m.thresholds?.catalogue_rejected_sigma;
  const agrees = head?.claim_type === "CONSISTENT_WITH";
  const step = (n, title, body, act = "") => `<li><span class="journey-n" aria-hidden="true">${n}</span><div><strong>${h(title)}</strong><p>${body}</p>${act}</div></li>`;
  return `<section class="journey" aria-labelledby="journey-title"><h3 id="journey-title">In plain terms</h3>
    <p class="journey-lead">${h(name)} was measured in ${h(cov.n_measured)} real SPHEREx images. Over the ${h(days)}-day fit baseline its position shifts by about
      ${h(fit.total.toFixed(1))}″ per year; ${h(catName)} predicts ${h(cat.total.toFixed(1))}″ per year. ${agrees ? "The two agree within the stated uncertainties." : `Headline verdict: ${h(label(head?.claim_type || "not available"))}.`}</p>
    <p class="journey-caveat">Provisional: method not yet validated on real data. Angular motion only; see “What this does not establish” below.</p>
    <ol class="journey-steps">
      ${step(1, "Real SPHEREx observations", `${h(cov.n_measured)} measured observations in ${h(cov.n_epochs)} epochs (MJD ${h(Math.floor(cov.mjd_min))}–${h(Math.floor(cov.mjd_max))}), each traceable to its archive product.`, `<button type="button" class="text-button" data-action="tab" data-id="evidence">Open the evidence</button>`)}
      ${step(2, "Measured motion", `Fitted ${h(fit.total.toFixed(2))} ± ${h(sigma.toFixed(2))}″/yr from ${h(m.n_usable)} usable images in ${h(m.n_epochs)} fit epochs; a stationary source is rejected at ${h(m.motion_detection_sigma.toFixed(1))}σ.`, `<button type="button" class="text-button" data-action="chart" data-id="motion">Show the motion chart</button>`)}
      ${step(3, `${catName} comparison`, `Catalogue proper motion ${h(cat.total.toFixed(2))}″/yr. The catalogue model is ${Number.isFinite(pCat) && Number.isFinite(thr) ? `${pCat < thr ? "not rejected" : "rejected"} (${h(pCat.toFixed(1))}σ against a ${h(thr)}σ threshold)` : "compared in the gated claim"}.`)}
      ${step(4, "Qualified conclusion", `${h(head?.statement || "The gated headline claim is loading.")}`)}
    </ol></section>`;
}

function runAnswer(state) {
  const doc = state.doc;
  const candidates = list(doc.candidates);
  return `${doc.data_origin === "SYNTHETIC" ? `<p class="synthetic-flag">SYNTHETIC · NOT REAL DATA</p>` : ""}
    <section class="quick-answer"><h3>Field result</h3><p>${candidates.length} candidate${candidates.length === 1 ? "" : "s"} for review from ${list(doc.observations).length} observations. Blind-pipeline outputs come from methods not validated on real data; ranking is review priority, never a probability of discovery.</p></section>
    ${statusChips(doc)}
    ${facts([["Observations", list(doc.observations).length], ["Pipeline detections", list(doc.detections).length], ["Associated sources", list(doc.sources).length], ["Candidates", candidates.length], ["Data origin", doc.data_origin]])}
    ${group("Candidates (review priority order)", stack(candidates.slice().sort((a, b) => (a.rank ?? 1e9) - (b.rank ?? 1e9)).map((c) =>
      action(label(c.kind), "candidate", c.candidate_id, [c.attention_level ? `attention ${label(c.attention_level)}` : "", c.candidate?.validity?.state].filter(Boolean).join(" · "))), "No candidates were recorded in this run."))}
    ${list(doc.warnings).length ? group("Limitations", list(doc.warnings).map(para).join("")) : ""}
    ${group("Next", stack([action("Export the saved run (.json)", "export-run")]))}`;
}

function coveragePage(state) {
  const c = state.coverage;
  const f = state.record.field;
  if (!c) return state.panelErrors.coverage ? empty(`Coverage unavailable: ${state.panelErrors.coverage}`, true) : empty("Checking indexed coverage…");
  return `<section class="quick-answer"><h3>Coverage only</h3><p>${h(label(c.readiness))}. Browsing reads the metadata index; it has not downloaded images or run any analysis.</p></section>
    ${para(c.message || c.note)}
    ${facts([["Requested cone", `${number(f.ra, 5)}, ${number(f.dec, 5)} r=${number(f.radius, 3)}°`], ["Queried cone", c.queried_cone ? `r=${number(c.queried_cone.radius_deg, 3)}° (${c.queried_cone.snapped ? "snapped to grid" : "exact"})` : null],
      ["Indexed observations (metadata)", c.n_observations], ["Index as of", c.index_as_of], ["Rows loaded", list(c.observations).length]])}
    <p class="compact">Metadata coverage ≠ downloaded data ≠ analysed data. Run an investigation explicitly to analyse this region.</p>
    ${c.job?.job_id ? stack([action("Track the index preparation job", "job", c.job.job_id)]) : ""}
    ${group("Run an analysis (explicit)", stack([action("Blind field run of this region…", "run-dialog", "field"), action("Motion test at this position…", "run-dialog", "MOVING_OBJECT"), action("Variability test at this position…", "run-dialog", "VARIABLE_STAR")]))}`;
}

export function regionBlock(state) {
  const r = state.region;
  if (!r) return "";
  const counts = {};
  for (const i of r.items) counts[i.kind] = (counts[i.kind] || 0) + 1;
  const summary = Object.entries(counts).map(([k, n]) => `${n} ${label(k).toLowerCase()}${n === 1 ? "" : "s"}`).join(", ") || "nothing selectable";
  return `<section class="region-block" aria-labelledby="region-title"><div class="section-line"><h3 id="region-title">Region selection · ${h(summary)}</h3><button type="button" class="text-button" data-action="clear-region">Clear</button></div>
    <p class="compact">${h(label(r.mode))} selection of plotted records${r.hidden ? `; ${r.hidden} plotted record(s) hidden by filters are not included` : ""}. Order: candidates, observations, detections, sources, then identifier.</p>
    ${stack(r.items.slice(0, 200).map((i) => action(i.label || i.id, i.kind, i.id, label(i.kind))), "No plotted record falls inside the region.")}
    ${r.items.length > 200 ? para(`${r.items.length - 200} more not listed.`) : ""}</section>`;
}

